/**
 ******************************************************************************
 * @file    ref_store.h
 * @brief   击打参考样本的 Flash 持久化（设备最后一页 2KB 专用页）。
 *
 * 用途：上电校准流程把"第一次正常击打"的锁帧合力样本存为参考，跨断电保留；
 * 后续击打与它做归一化互相关（Pearson），按相关度判真伪。
 *
 * 掉电安全策略（2026-10-17 方案 B：页内始终以"有效内容或全 0xFF"结束，绝不出现
 * 半写状态被误用）：
 *   上电  RefStore_Load()：**只读**——校验 → 拷到 RAM，不擦页。旧参考一直留在 Flash
 *         里，直到本上电训练写入时才被覆盖；
 *   训练  RefStore_Save()：先擦页再编程（擦 ~25ms + 写 ~6ms，落在 50ms 不应期内）。
 * 于是**任意非写入时刻掉电都不丢参考**（上电瞬间、校准期间、正常运行中全部安全）；
 * 仅写入进行中掉电（~31ms，每上电最多一次）→ 页损坏 → 下次上电走首次训练路径。
 * 每上电最多 1 次擦除 + 1 次编程，Flash 寿命无忧。
 *
 * 调用约束：
 *   - `RefStore_Load` 纯读，App_Init 内调用即可（无阻塞，时序宽松）；
 *   - `RefStore_Save` 含页擦除 + 编程（~31ms 阻塞），只能在**主循环上下文**调用，
 *     禁止 ISR；
 *   - 阻塞期间 DRDY/DMA 仍会推进，主循环按 drop_cnt 自恢复（管线不依赖零丢帧）。
 ******************************************************************************
 */
#ifndef APP_BSP_REF_STORE_H
#define APP_BSP_REF_STORE_H

#include <stdint.h>
#include <stdbool.h>

/* 单次可存取的样本数上限（与 detect 层冻结窗上限同量级，当前锁帧窗 64） */
#define REF_STORE_MAX  128u

/* 上电载入：校验末页内容，有效则把样本拷入 sum（容量须 ≥ REF_STORE_MAX）
 * 并写回 *n。**不擦页**——旧内容保留至本上电训练写入时被覆盖。
 * 返回 true = 拿到了有效参考。sum/n 任一为 NULL 时直接返回 false 且不碰 Flash。 */
bool RefStore_Load(int32_t *sum, uint16_t *n);

/* 落盘（先擦页再编程，~31ms 阻塞，仅主循环上下文、禁止 ISR）。
 * 返回 0 = 成功，-1 = 参数非法/擦除失败/编程失败；擦除失败时页保留旧内容。 */
int  RefStore_Save(const int32_t *sum, uint16_t n);

/* 诊断标量（Ozone 直接 watch）：0=无错，1=擦除失败，2=编程失败，3=解锁失败 */
uint32_t RefStore_GetErr(void);

#endif /* APP_BSP_REF_STORE_H */
